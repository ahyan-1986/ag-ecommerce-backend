type ProductHandler struct {
	productSvc domain.ProductService
}

func NewProductHandler(productSvc domain.ProductService) *ProductHandler {
	return &ProductHandler{productSvc: productSvc}
}

// Public endpoints (no auth required)

func (h *ProductHandler) ListPublicProducts(c *gin.Context) {
	category := c.Query("category")
	search := c.Query("search")
	page, _ := strconv.Atoi(c.DefaultQuery("page", "1"))
	pageSize, _ := strconv.Atoi(c.DefaultQuery("pageSize", "20"))

	products, total, err := h.productSvc.ListPublishedProducts(category, search, page, pageSize)
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}
	c.JSON(http.StatusOK, gin.H{"items": products, "total": total, "page": page, "pageSize": pageSize})
}

func (h *ProductHandler) GetPublicProduct(c *gin.Context) {
	id, err := uuid.Parse(c.Param("id"))
	if err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "invalid product ID"})
		return
	}
	p, err := h.productSvc.GetProduct(id)
	if err != nil || p.Status != domain.ProductStatusPublished {
		c.JSON(http.StatusNotFound, gin.H{"error": "product not found"})
		return
	}
	c.JSON(http.StatusOK, p)
}

